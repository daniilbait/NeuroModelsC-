namespace MO32_1_Daniil.NeuroNet
{
    enum MemoryMode
    {   // Режим работы с синаптическими весами (оценками, которые нейрон даёт сигналам нейронов предыдущего слоя) каждого слоя
        GET,    // считывание файлов синаптических весов
        SET,    // сохранение синаптических весов в файл
        INIT    // создание новых файлов со случайными весами
    }
    enum NeuronType
    {   // Тип нейрона — определяет функцию активации: скрытый слой (tanh) или выходной (экспонента для softmax)
        Hidden, // Скрытый слой — активация tanh; градиент = ошибка * производная, ошибка = сумма (градиент нейрона след.слоя на вес данного у нейрона след.слоя)
        Output  // Выходной слой — активация экспонентой, затем нормировка в проценты (softmax); градиент = ошибка = ожидание − фактический отклик
    }
    enum NetworkMod
    {   // Режимы работы нейросети
        Train,  // Режим тренировки (настройка синаптических весов)
        Test,   // Режим тестирования (проверка, что веса настроены верно на отдельных примерах)
        Demo    // ?
    }
}
